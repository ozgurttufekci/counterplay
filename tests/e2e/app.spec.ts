test('license and exact engine source assets are present in the deployed subpath', async ({ page, request }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'How it works' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  for (const asset of ['THIRD-PARTY-NOTICES.txt', 'stockfish/COPYING.txt', 'stockfish/SOURCE.txt', 'stockfish/nn-61e7af4bb97d.nnue', 'stockfish/stockfish-source-54fde71d90c7c403964f6cacef48f7bbec495df1.tar.gz']) {
    const response = await request.get(asset)
    expect(response.status(), asset).toBe(200)
    expect(response.headers()['content-type'], asset).not.toContain('text/html')
  }
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
