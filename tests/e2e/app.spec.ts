test('handicaps, color swapping, validation, exports, and local preferences', async ({ page }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Bishop odds.' })).toBeVisible()
  const setup = page.getByLabel('Starting position FEN')
  expect(new Chess(await setup.inputValue()).get('c8')).toBeUndefined()
  await page.getByRole('button', { name: 'Swap colors', exact: true }).click()
  expect(new Chess(await setup.inputValue()).get('c1')).toBeUndefined()
  await page.getByRole('button', { name: 'Rook', exact: true }).click()
  expect(new Chess(await setup.inputValue()).getCastlingRights('w')).toEqual({ k: true, q: false })
  await page.getByRole('button', { name: 'Reset suggestion', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bishop odds.' })).toBeVisible()

  await page.getByLabel('Player one name').fill('Ada')
  await page.getByLabel('Player one rating').fill('1600.5')
  await expect(page.getByRole('alert')).toContainText('whole-number')
  await expect(page.getByRole('heading', { name: "Let's start with two valid ratings." })).toBeVisible()
  await page.getByLabel('Player one rating').fill('1600')
  await expect(page.getByRole('heading', { name: 'Even material.' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Player one name')).toHaveValue('Ada')
  await expect(page.getByLabel('Player one rating')).toHaveValue('1600')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export PGN', exact: true }).click()
  const download = await downloadEvent
  const path = await download.path()
  if (!path) throw new Error('PGN download did not create a file')
  const chess = new Chess()
  chess.loadPgn(await readFile(path, 'utf8'))
  expect(chess.fen()).toBe(await setup.inputValue())
  expect(chess.getHeaders().White === 'Ada' || chess.getHeaders().Black === 'Ada').toBe(true)

  await page.getByLabel('Player one rating').fill('100')
  await page.getByLabel('Player two rating').fill('3500')
  await expect(page.getByText(/outside the model's useful confidence range/)).toBeVisible()
})

test('fresh workers at a subpath, queued generation, hints, wrong moves, click/drag/keyboard solving, and replay', async ({ page }) => {
  const external: string[] = []
  page.on('request', (request) => { if (!request.url().startsWith('http://127.0.0.1:4173/')) external.push(request.url()) })
  await seedGeneration(page, [1002, 1011])
  await page.goto('./')
  await page.getByRole('tab', { name: 'Puzzle Lab' }).click()
  const white = page.getByRole('region', { name: 'White puzzle', exact: true })
  const black = page.getByRole('region', { name: 'Black puzzle', exact: true })
  await white.getByLabel('White puzzle objective').selectOption('mate')
  await white.getByLabel('White puzzle difficulty').selectOption('deep')
  await black.getByLabel('Black puzzle difficulty').selectOption('balanced')
  await white.getByRole('button', { name: 'Generate puzzle', exact: true }).click()
  await black.getByRole('button', { name: 'Generate puzzle', exact: true }).click()
  await expect(black.getByText(/Queued behind the other puzzle/)).toBeVisible()
  const wp = await waitForPuzzle(page, 'w')
  const bp = await waitForPuzzle(page, 'b')
  expect(wp.seed).toBe(1002)
  expect(wp.objective.plies).toBe(3)
  expect(bp.seed).toBe(1011)
  expect(external).toEqual([])
  await expect(white.getByRole('button', { name: 'Export solution PGN' })).toHaveCount(0)

  const wrong = new Chess(wp.fen).moves({ verbose: true }).find((move) => uci(move) !== wp.firstMove)
  if (!wrong) throw new Error('Missing wrong-move test case')
  await white.getByLabel('Enter a move').fill(uci(wrong))
  await white.getByRole('button', { name: 'Play typed move' }).click()
  await expect(white.getByRole('alert')).toContainText('defense')
  await white.getByRole('button', { name: 'Hint', exact: true }).click()
  await expect(white.getByText(`Look closely at the piece on ${wp.firstMove.slice(0, 2)}.`)).toBeVisible()
  await white.locator(`.square-hit[data-square="${wp.firstMove.slice(0, 2)}"]`).click()
  await white.locator(`.square-hit[data-square="${wp.firstMove.slice(2, 4)}"]`).click()
  await expect(white.getByText('Good move. The opponent has replied; find your continuation.')).toBeVisible()
  await expect(white.getByText('NICELY PLAYED')).toHaveCount(0)
  const grade = gradeMove(wp, [], wp.firstMove)
  const next = grade.continuation[0]
  if (!next) throw new Error('The mate in two needs a continuation')
  await white.getByLabel('Enter a move').fill(next)
  await white.getByLabel('Enter a move').press('Enter')
  await expect(white.getByText('NICELY PLAYED')).toBeVisible()
  await expect(white.getByRole('button', { name: 'Export solution PGN' })).toBeVisible()
  await white.getByRole('button', { name: 'Review solution' }).click()
  await white.getByRole('button', { name: 'Next move' }).click()
  await expect(white.getByText('1 / 3 plies')).toBeVisible()
  await white.getByRole('button', { name: 'Reset White puzzle' }).click()
  await expect(white.getByLabel('Enter a move')).toBeVisible()
  await expect(white.getByText('NICELY PLAYED')).toHaveCount(0)

  await dragMove(page, black, bp.firstMove)
  await expect(black.getByText('NICELY PLAYED')).toBeVisible()
  await page.reload()
  expect((await savedPuzzles(page)).map((puzzle) => puzzle.id).sort()).toEqual([wp.id, bp.id].sort())
  await expect(white.getByRole('heading', { name: 'White to move. Force mate in 2.' })).toBeVisible()
})

test('cancels an active search without poisoning the queue or the next engine', async ({ page }) => {
  await seedGeneration(page, [10000, 1011, 1001])
  await page.goto('./')
  await page.getByRole('tab', { name: 'Puzzle Lab' }).click()
  const white = page.getByRole('region', { name: 'White puzzle', exact: true })
  const black = page.getByRole('region', { name: 'Black puzzle', exact: true })
  await white.getByLabel('White puzzle objective').selectOption('mate')
  await white.getByLabel('White puzzle difficulty').selectOption('gentle')
  await white.getByRole('button', { name: 'Generate puzzle', exact: true }).click()
  await black.getByRole('button', { name: 'Generate puzzle', exact: true }).click()
  await white.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(white.getByText('Search canceled. Your current puzzle is unchanged.')).toBeVisible()
  await waitForPuzzle(page, 'b')
  await white.getByLabel('White puzzle difficulty').selectOption('balanced')
  await white.getByRole('button', { name: 'Generate puzzle', exact: true }).click()
  expect((await waitForPuzzle(page, 'w')).seed).toBe(1001)
})

